import { Meteor } from 'meteor/meteor';

import { SystemLogger } from '../../lib/logger/system';
import { settings } from '../../settings';

import type { APIActionContext } from '../router';  // n.b. generated by apps/meteor/server/api/router.ts:convertHonoContextToApiActionContext

export function logMethodCallError(method: string, err: unknown, apiActionContext: APIActionContext): void {
	if ((err as any)?.isClientSafe || (err as any)?.meteorError) {
		SystemLogger.debug({ msg: 'Expected error while invoking method', err, method });
		return;
	}

	SystemLogger.error({ msg: 'Exception while invoking method', err, method });

	if (settings.get('Log_Level') === '2') {
		Meteor._debug(
			`Exception while invoking method ${method}`,
			err,
			{
				method,
				params,
				userId: apiActionContext.userId,
				userName: apiActionContext.user?.username,
				userAgent: apiActionContext.request?.headers?.get('user-agent'),
				requestedWith: apiActionContext.request?.headers?.get('X-Requested-With'),
				referer: apiActionContext.request?.headers?.get('referer'),
				err,
				apiActionContext,
			},
		);
	}
}
